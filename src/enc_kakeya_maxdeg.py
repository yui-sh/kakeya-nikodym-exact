#!/usr/bin/env python3
"""Fresh encoder for the max-degree reduction of K(3,q) (used for K(3,3)=13 and K(3,4)=28).

Statement proved when every subcase is UNSAT at ub = K-1:  no Kakeya set of size <= K-1 exists in AG(3,q).

Reduction (hand proof, README section "K(3,4)"):
  1. If a Kakeya set of size <= ub exists, so does a union K of one line per direction (a
     'witness system') with |K| <= ub.
  2. Let d_p = number of witness lines through p, D = max_p d_p.  Sum_p d_p = nd*q where
     nd = q^2+q+1 directions, so D >= ceil(nd*q/ub); the D lines through a max-degree point
     cover 1+(q-1)D points, so 1+(q-1)D <= ub.
  3. A translation moves a max-degree point O to the origin; a semilinear map g in GammaL(3,q)
     (a collineation fixing the origin) replaces the set R of D directions through O by g(R).
     Hence R may be taken to be the chosen representative of its orbit under the group G generated
     by the generators below.  SOUNDNESS ONLY NEEDS: (a) every generator is a collineation
     (checked here: every line maps onto a line), (b) the orbits of the representatives cover
     all D-subsets (checked here: orbit sizes sum to C(nd,D)).  Whether G is all of PGammaL(3,q)
     is irrelevant (a smaller group only yields more subcases).
  4. Subcase (D,R) CNF: variables x_p (p in K), y_l (l chosen witness line);
     (i) exactly one y per direction; (ii) y_l -> x_p for p on l; (iii) x_p -> OR of y_l, l through p;
     (iv) at most D chosen lines through every point; (v) y_l = 1 for the D lines through the origin
     with directions in R; (vi) sum x_p <= ub.
usage: enc_kakeya_maxdeg.py --q 4 --ub 27 --list
       enc_kakeya_maxdeg.py --q 4 --ub 27 --D 4 --rep 0 --out case.cnf [--meta case.json]
       enc_kakeya_maxdeg.py --q 4 --ub 27 --D 4 --rep 0 --model model.txt   (decode a SAT model -> points JSON on stdout)
"""
import argparse, itertools, json, sys
from math import comb
from ag import AG
import card


def collineation_generators(g):
    """Generators of GammaL(3,q) as point permutations; each is verified to map lines to lines."""
    F, q = g.F, g.q
    mats = []
    for i in range(3):
        for j in range(3):
            if i != j:  # transvection E_ij(1)
                M = [[int(r == c) for c in range(3)] for r in range(3)]
                M[i][j] = 1
                mats.append(M)
    if q > 2:
        prim = next(a for a in range(2, q) if len({F.power(a, k) for k in range(q - 1)}) == q - 1)
        for i in range(3):
            M = [[int(r == c) for c in range(3)] for r in range(3)]
            M[i][i] = prim
            mats.append(M)
    perms = []
    for M in mats:
        perms.append([g.pidx[tuple(g.dot(M[r], p) for r in range(3))] for p in g.points])
    if F.k > 1:
        perms.append([g.pidx[tuple(F.frob[c] for c in p)] for p in g.points])
    for perm in perms:  # verify: bijection fixing the origin and mapping every line onto a line
        assert sorted(perm) == list(range(len(g.points))) and perm[g.pidx[(0, 0, 0)]] == g.pidx[(0, 0, 0)]
        for _, pts in g.lines:
            assert frozenset(perm[p] for p in pts) in g.line_of
    return perms


def direction_perms(g, perms):
    out = []
    for perm in perms:
        dp = [g.didx[g.normalize(g.points[perm[g.pidx[d]]])] for d in g.dirs]
        assert sorted(dp) == list(range(len(g.dirs)))
        out.append(dp)
    return out


def orbits(nd, dperms, D):
    """orbits of D-subsets of range(nd) under the group generated by dperms: list of (rep, size)"""
    seen = set()
    res = []
    for comb_ in itertools.combinations(range(nd), D):
        if comb_ in seen:
            continue
        orb = {comb_}
        stack = [comb_]
        while stack:
            s = stack.pop()
            for p in dperms:
                t = tuple(sorted(p[i] for i in s))
                if t not in orb:
                    orb.add(t)
                    stack.append(t)
        seen |= orb
        res.append((min(orb), len(orb)))
    assert sum(sz for _, sz in res) == comb(nd, D) and len(seen) == comb(nd, D)
    return res


def degree_range(g, ub):
    nd, q = len(g.dirs), g.q
    Dmin = -(-nd * q // ub)
    Dmax = (ub - 1) // (q - 1)
    return Dmin, Dmax


def max_coplanar(g, R):
    return max(sum(1 for d in R if g.dot(nv, g.dirs[d]) == 0) for nv in g.dirs)


def build_cnf(g, D, R, ub, broken=None):
    """broken: deliberately wrong encodings used as controls --
       'drop-cap' omits the size cap (too weak: SAT at ub = K-1 where UNSAT is expected; the decoded
       model is a Kakeya set but larger than ub, which the size check of the control table catches);
       'extra-cap' lowers the size cap by one (too strong: the positive control at ub = K becomes UNSAT)."""
    P, L = len(g.points), len(g.lines)
    if broken == "extra-cap":
        ub -= 1
    x = lambda p: p + 1
    y = lambda l: P + l + 1
    top = P + L
    cls = []
    for di in range(len(g.dirs)):
        ls = g.lines_by_dir[di]
        cls.append([y(l) for l in ls])
        cls += [[-y(a), -y(b)] for a, b in itertools.combinations(ls, 2)]
    for l, (_, pts) in enumerate(g.lines):
        for p in pts:
            cls.append([-y(l), x(p)])
    for p in range(P):
        cls.append([-x(p)] + [y(l) for l in g.lines_through[p]])
        c, top = card.atmost([y(l) for l in g.lines_through[p]], D, top)
        cls += c
    for d in R:
        cls.append([y(g.line_through((0, 0, 0), g.dirs[d]))])
    if broken != "drop-cap":
        c, top = card.atmost([x(p) for p in range(P)], ub, top)
        cls += c
    return top, cls


def all_cases(g, ub):
    dperms = direction_perms(g, collineation_generators(g))
    Dmin, Dmax = degree_range(g, ub)
    return [(D, orbits(len(g.dirs), dperms, D)) for D in range(Dmin, Dmax + 1)]


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--q", type=int, required=True)
    ap.add_argument("--ub", type=int, required=True)
    ap.add_argument("--D", type=int)
    ap.add_argument("--rep", type=int)
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--out")
    ap.add_argument("--meta")
    ap.add_argument("--model", help="SAT model file (DIMACS 'v' lines); print the point set as JSON")
    ap.add_argument("--broken", choices=["drop-cap", "extra-cap"], help="deliberately broken encoding (control)")
    a = ap.parse_args()
    g = AG(3, a.q)
    cases = all_cases(g, a.ub)
    if a.list:
        tot = 0
        for D, orbs in cases:
            print(f"D={D}: {len(orbs)} orbits (sizes sum to C({len(g.dirs)},{D})={comb(len(g.dirs), D)}); forced points 1+{a.q-1}*{D}={1+(a.q-1)*D}")
            for i, (rep, sz) in enumerate(orbs):
                print(f"  rep {i}: dirs {[''.join(map(str, g.dirs[d])) for d in rep]} orbit size {sz} max_coplanar {max_coplanar(g, rep)}")
            tot += len(orbs)
        print(f"total subcases: {tot}")
        sys.exit(0)
    orbs = dict(cases)[a.D]
    rep, sz = orbs[a.rep]
    nv, cls = build_cnf(g, a.D, rep, a.ub, a.broken)
    if a.model:
        lits = set()
        for line in open(a.model):
            if line.startswith("v"):
                lits.update(int(t) for t in line.split()[1:])
        pts = [list(g.points[p]) for p in range(len(g.points)) if (p + 1) in lits]
        print(json.dumps({"n": 3, "q": a.q, "points": pts, "D": a.D, "rep": a.rep, "ub": a.ub}))
        sys.exit(0)
    card.write_dimacs(a.out, nv, cls, [f"kakeya maxdeg q={a.q} ub={a.ub} D={a.D} rep={a.rep} dirs={[g.dirs[d] for d in rep]} broken={a.broken}"])
    meta = dict(q=a.q, ub=a.ub, D=a.D, rep=a.rep, dirs=[g.dirs[d] for d in rep], orbit_size=sz,
                max_coplanar=max_coplanar(g, rep), nvars=nv, nclauses=len(cls))
    if a.meta:
        json.dump(meta, open(a.meta, "w"))
    print(json.dumps(meta))
