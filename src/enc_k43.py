#!/usr/bin/env python3
"""Fresh encoder for K(4,3) = 27 (Kakeya sets in AG(4,3)).

Two kinds of CNF:
 (1) capacity instances  cap_k_r : 'some X in F_3^3 with |X| <= k contains a full line in >= r
     directions'.  UNSAT  =>  f(k) <= r-1 (the table used by k43_reduction.py).  WLOG one fixed
     line (the x-axis) is inside X: X contains a line if r >= 1, and the collineation group used
     here is transitive on lines (checked: the orbit of the x-axis under the generators is all 117 lines).
 (2) case instances  case_a_b_c_rep : S in AG(4,3) is Kakeya (one full line per direction),
     the slice x4=0 is EXACTLY the representative set (|rep| = a), slice x4=1 has exactly b points,
     slice x4=2 exactly c points.  UNSAT for all (type, rep)  =>  no 26-point Kakeya set.
     WLOG justification: the smallest slice may be moved to x4=0 and the other two swapped by the
     affine maps x4 -> x4+t, x4 -> -x4 of the last coordinate; an affine map of F_3^3 applied to the
     first three coordinates fixes every layer, so the smallest slice may be replaced by the
     representative of its orbit under the group G generated by the generators below.
     SOUNDNESS ONLY NEEDS (checked here): each generator is an affine collineation of AG(3,3) and
     the orbits of the representatives cover all C(27,a) subsets.
usage: enc_k43.py --cap k r --out f.cnf
       enc_k43.py --orbits a            (print representatives and orbit sizes)
       enc_k43.py --case a b c rep_index --out f.cnf
       enc_k43.py --spec DIR            (print JSON batch spec of the 67 case instances + 10 capacity instances)
       enc_k43.py --decode-cap k r --model m.txt   /  --decode-case ... --model m.txt
"""
import argparse, itertools, json, sys
from math import comb
from ag import AG
import card

TYPES = [(4, 9, 13), (4, 10, 12), (5, 7, 14), (5, 8, 13), (5, 9, 12), (6, 6, 14), (6, 7, 13), (6, 8, 12), (7, 7, 12)]
F_TABLE = {3: 1, 4: 1, 5: 2, 6: 3, 7: 4, 8: 4, 9: 6, 10: 7, 11: 9, 12: 10}


def affine_generators(g):
    """generators of AGL(3,3) as point permutations of AG(3,3); each verified to map lines onto lines"""
    perms = []
    for i in range(3):  # translations by unit vectors
        e = tuple(int(j == i) for j in range(3))
        perms.append([g.pidx[g.add(p, e)] for p in g.points])
    mats = []
    for i in range(3):
        for j in range(3):
            if i != j:
                M = [[int(r == c) for c in range(3)] for r in range(3)]
                M[i][j] = 1
                mats.append(M)
    M = [[int(r == c) for c in range(3)] for r in range(3)]
    M[0][0] = 2
    mats.append(M)
    for M in mats:
        perms.append([g.pidx[tuple(g.dot(M[r], p) for r in range(3))] for p in g.points])
    for perm in perms:
        assert sorted(perm) == list(range(27))
        for _, pts in g.lines:
            assert frozenset(perm[p] for p in pts) in g.line_of
    return perms


def line_transitive(g, perms):
    start = g.line_through((0, 0, 0), (1, 0, 0))
    seen = {start}
    stack = [start]
    while stack:
        l = stack.pop()
        for perm in perms:
            img = g.line_of[frozenset(perm[p] for p in g.lines[l][1])]
            if img not in seen:
                seen.add(img)
                stack.append(img)
    return len(seen) == len(g.lines)


def subset_orbits(g, perms, k):
    """orbits of k-subsets of the 27 points (as bitmasks) under <perms>; returns [(min_mask, size)]"""
    shifted = [[1 << perm[i] for i in range(27)] for perm in perms]

    def act(mask, s):
        r = 0
        i = 0
        while mask:
            if mask & 1:
                r |= s[i]
            mask >>= 1
            i += 1
        return r
    seen = set()
    res = []
    for c in itertools.combinations(range(27), k):
        m0 = sum(1 << i for i in c)
        if m0 in seen:
            continue
        orb = {m0}
        stack = [m0]
        while stack:
            m = stack.pop()
            for s in shifted:
                t = act(m, s)
                if t not in orb:
                    orb.add(t)
                    stack.append(t)
        seen |= orb
        res.append((min(orb), len(orb)))
    assert len(seen) == comb(27, k) and sum(sz for _, sz in res) == comb(27, k)
    return res


def capacity_cnf(k, r):
    g = AG(3, 3)
    P, L, ND = 27, len(g.lines), len(g.dirs)
    x = lambda p: p + 1
    y = lambda l: P + l + 1
    z = lambda d: P + L + d + 1
    top = P + L + ND
    cls = []
    for l, (_, pts) in enumerate(g.lines):
        for p in pts:
            cls.append([-y(l), x(p)])
    for d in range(ND):
        cls.append([-z(d)] + [y(l) for l in g.lines_by_dir[d]])
    c, top = card.atmost([x(p) for p in range(P)], k, top)
    cls += c
    c, top = card.atleast([z(d) for d in range(ND)], r, top)
    cls += c
    cls.append([y(g.line_through((0, 0, 0), (1, 0, 0)))])
    return top, cls, g


def case_cnf(a, b, c, rep_mask):
    g3 = AG(3, 3)
    g = AG(4, 3)
    P, L = 81, len(g.lines)
    x = lambda p: p + 1
    y = lambda l: P + l + 1
    top = P + L
    cls = []
    for d in range(len(g.dirs)):
        cls.append([y(l) for l in g.lines_by_dir[d]])
    for l, (_, pts) in enumerate(g.lines):
        for p in pts:
            cls.append([-y(l), x(p)])
    assert bin(rep_mask).count("1") == a
    for i, p in enumerate(g.points):
        if p[3] == 0:
            inrep = (rep_mask >> g3.pidx[p[:3]]) & 1
            cls.append([x(i)] if inrep else [-x(i)])
    for t, k in ((1, b), (2, c)):
        lits = [x(i) for i, p in enumerate(g.points) if p[3] == t]
        cc, top = card.equals(lits, k, top)
        cls += cc
    return top, cls, g


def read_model(path):
    lits = set()
    for line in open(path):
        if line.startswith("v"):
            lits.update(int(t) for t in line.split()[1:])
    return lits


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--cap", nargs=2, type=int)
    ap.add_argument("--orbits", type=int)
    ap.add_argument("--case", nargs=4, type=int)
    ap.add_argument("--spec")
    ap.add_argument("--out")
    ap.add_argument("--model")
    a = ap.parse_args()
    if a.orbits or a.case or a.spec:
        g3 = AG(3, 3)
        perms = affine_generators(g3)
        assert line_transitive(g3, perms)
    if a.orbits:
        orbs = subset_orbits(g3, perms, a.orbits)
        print(json.dumps({"k": a.orbits, "n_orbits": len(orbs), "reps": [{"mask": m, "size": s, "points": [g3.points[i] for i in range(27) if m >> i & 1]} for m, s in orbs]}))
    elif a.cap:
        k, r = a.cap
        nv, cls, g = capacity_cnf(k, r)
        if a.model:
            lits = read_model(a.model)
            X = [g.points[p] for p in range(27) if (p + 1) in lits]
            dirs_hit = [g.dirs[d] for d in range(len(g.dirs)) if any(all(((p + 1) in lits) for p in g.lines[l][1]) for l in g.lines_by_dir[d])]
            print(json.dumps({"k": k, "r": r, "X": X, "size": len(X), "directions_with_full_line": len(dirs_hit)}))
        else:
            card.write_dimacs(a.out, nv, cls, [f"K(4,3) capacity instance: |X|<={k} points of AG(3,3) with full lines in >= {r} directions (x-axis fixed)"])
            print(json.dumps({"cap": [k, r], "nvars": nv, "nclauses": len(cls)}))
    elif a.case:
        aa, bb, cc, ri = a.case
        orbs = subset_orbits(g3, perms, aa)
        mask, size = orbs[ri]
        nv, cls, g = case_cnf(aa, bb, cc, mask)
        if a.model:
            lits = read_model(a.model)
            S = [list(g.points[p]) for p in range(81) if (p + 1) in lits]
            print(json.dumps({"n": 4, "q": 3, "points": S, "case": [aa, bb, cc, ri]}))
        else:
            card.write_dimacs(a.out, nv, cls, [f"K(4,3) case: slices ({aa},{bb},{cc}), slice x4=0 fixed to orbit rep {ri} (mask {mask}, orbit size {size})"])
            print(json.dumps({"case": [aa, bb, cc, ri], "rep_mask": mask, "orbit_size": size, "nvars": nv, "nclauses": len(cls)}))
    elif a.spec:
        spec = []
        for k, fk in F_TABLE.items():
            name = f"cap_{k}_{fk+1}"
            spec.append({"name": name, "gen": ["python3", "enc_k43.py", "--cap", str(k), str(fk + 1), "--out", f"{a.spec}/{name}.cnf"]})
        norb = {}
        for (aa, bb, cc) in TYPES:
            if aa not in norb:
                norb[aa] = len(subset_orbits(g3, perms, aa))
            for ri in range(norb[aa]):
                name = f"case_{aa}_{bb}_{cc}_r{ri}"
                spec.append({"name": name, "gen": ["python3", "enc_k43.py", "--case", str(aa), str(bb), str(cc), str(ri), "--out", f"{a.spec}/{name}.cnf"]})
        print(json.dumps(spec, indent=0))
        print(json.dumps({"orbit_counts": norb, "n_cases": sum(norb[t[0]] for t in TYPES)}), file=sys.stderr)
