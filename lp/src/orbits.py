"""Enumerate ALL minimum Kakeya sets (given the proven minimum k) in AG(n,q) and classify
them up to the affine group AGL(n,q): number of classes, orbit sizes, stabilizer orders.
Method: SAT enumeration (blocking clauses) of all k-sets containing the fixed line
{t e_1} (WLOG, as AGL is transitive on lines), then orbit BFS under generators of AGL.
Generators are validated by checking the orbit of an affine frame has size |AGL(n,q)|.
Usage: python orbits.py --n 3 --q 3 --k 13"""
import argparse, json, time, itertools
from pysat.solvers import Solver
from pysat.card import CardEnc, EncType
from pysat.formula import IDPool
from geom import AG, is_kakeya

def agl_order(n, q):
    g = q ** n
    for i in range(n):
        g *= q ** n - q ** i
    return g

def generators(ag):
    """Affine maps as point-index permutations (lists)."""
    n, q, F = ag.n, ag.q, ag.F
    def matvec(A, v):
        out = []
        for i in range(n):
            s = 0
            for j in range(n):
                s = F.add[s][F.mul[A[i][j]][v[j]]]
            out.append(s)
        return tuple(out)
    gens = []
    def add_affine(A, b):
        perm = [ag.pidx[ag.add(matvec(A, p), b)] for p in ag.points]
        gens.append(perm)
    I = [[int(i == j) for j in range(n)] for i in range(n)]
    for i in range(n):
        add_affine(I, ag.unit(i))
    for i in range(n):
        for j in range(n):
            if i != j:
                for c in range(1, q):
                    A = [row[:] for row in I]; A[i][j] = c
                    add_affine(A, (0,) * n)
    for i in range(n):
        for c in range(2, q):
            A = [row[:] for row in I]; A[i][i] = c
            add_affine(A, (0,) * n)
    return gens

def orbit(S, gens):
    """orbit of frozenset S under group generated by gens (as point perms)."""
    seen = {S}
    stack = [S]
    while stack:
        T = stack.pop()
        for g in gens:
            U = frozenset(g[p] for p in T)
            if U not in seen:
                seen.add(U); stack.append(U)
    return seen

def validate_generators(ag, gens):
    """orbit of an ordered affine frame must have size |AGL(n,q)| (regular action)."""
    n = ag.n
    frame = tuple([ag.pidx[(0,) * n]] + [ag.pidx[ag.unit(i)] for i in range(n)])
    seen = {frame}; stack = [frame]
    while stack:
        T = stack.pop()
        for g in gens:
            U = tuple(g[p] for p in T)
            if U not in seen:
                seen.add(U); stack.append(U)
    assert len(seen) == agl_order(n, ag.q), (len(seen), agl_order(n, ag.q))

def enumerate_optima(ag, k, limit=10**6):
    pool = IDPool()
    x = [pool.id(("x", i)) for i in range(len(ag.points))]
    y = [pool.id(("y", i)) for i in range(len(ag.lines))]
    cls = [[y[l] for l in ag.lines_by_dir[di]] for di in range(len(ag.dirs))]
    for l, (di, pts) in enumerate(ag.lines):
        for p in pts:
            cls.append([-y[l], x[p]])
    cls.append([y[ag.line_through((0,) * ag.n, ag.unit(0))]])
    cls += CardEnc.atmost(lits=x, bound=k, vpool=pool, encoding=EncType.totalizer).clauses
    sols = []
    with Solver(name="cadical153", bootstrap_with=cls) as s:
        while s.solve():
            model = set(v for v in s.get_model() if v > 0)
            S = frozenset(i for i in range(len(ag.points)) if x[i] in model)
            assert len(S) == k and is_kakeya(ag, S)[0]
            sols.append(S)
            s.add_clause([-x[i] for i in S])   # block this point set (any y)
            if len(sols) >= limit:
                break
    return sols

def invariants(ag, S):
    inside = [l for l, (di, pts) in enumerate(ag.lines) if pts <= S]
    deg = [0] * len(ag.points)
    for l in inside:
        for p in ag.lines[l][1]:
            deg[p] += 1
    return (len(inside), tuple(sorted(deg[p] for p in S)))

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, required=True)
    ap.add_argument("--q", type=int, required=True)
    ap.add_argument("--k", type=int, required=True, help="proven minimum size")
    a = ap.parse_args()
    t0 = time.time()
    ag = AG(a.n, a.q)
    gens = generators(ag)
    validate_generators(ag, gens)
    G = agl_order(a.n, a.q)
    sols = enumerate_optima(ag, a.k)
    print(f"n={a.n} q={a.q} k={a.k}: {len(sols)} optimal sets containing the fixed line ({time.time()-t0:.1f}s)")
    classes = []   # list of dict(rep, orbit set, invariants)
    for S in sols:
        inv = invariants(ag, S)
        if any(S in c["orbit"] for c in classes):
            continue
        orb = orbit(S, gens)
        classes.append({"rep": S, "orbit": orb, "inv": inv})
    nlines = len(ag.lines)
    out = {"n": a.n, "q": a.q, "k": a.k, "num_fixed_line_solutions": len(sols), "agl_order": G,
           "num_classes": len(classes), "classes": []}
    total = 0
    for c in classes:
        osz = len(c["orbit"]); total += osz
        out["classes"].append({"orbit_size": osz, "stabilizer_order": G // osz,
                               "lines_inside": c["inv"][0], "point_line_degrees": list(c["inv"][1]),
                               "rep": [ag.points[i] for i in sorted(c["rep"])]})
        print(f"  class: orbit {osz}, |Stab|={G//osz}, lines inside={c['inv'][0]}, degrees={c['inv'][1]}")
    out["total_optimal_sets"] = total
    # consistency: sets containing a given line, summed over classes, times #lines / (lines inside) ... just report
    print(f"  total optimal sets in AG({a.n},{a.q}): {total}  ({time.time()-t0:.1f}s)")
    json.dump(out, open(f"out/orbits_n{a.n}_q{a.q}.json", "w"), indent=1)
