"""K(3,q) exact attack by the max-degree WLOG (session III, see WRITEUP3.md).
Any Kakeya set K with |K| <= ub contains a union K' of one witness line per direction with
|K'| <= ub, so WLOG K is such a union. Let d_p = # witness lines through p and D = max_p d_p.
WLOG (translation) a point O = origin attains D; WLOG (GammaL(3,q), semilinear maps preserve lines)
the set of D directions through O is a fixed representative of its orbit under PGammaL(3,q) on PG(2,q).
Subcase (D, R): the D lines through the origin in directions R are witnesses, every point has degree <= D,
|union| <= ub.  All subcases INFEASIBLE  <=>  K(3,q) > ub.
Cuts (all valid, proofs in WRITEUP3): planar f-table (plane_f.py), projection (>= BM(q) lines of every
direction meet K).
Usage: maxdeg.py --q 4 --ub 27 --D 4 --rep 0 [--time T] [--workers W] [--planes] [--proj] [--cnf file]
       maxdeg.py --q 4 --list       (orbit table)"""
import argparse, json, time, sys, itertools
from geom import AG, is_kakeya
from structure import _dot

def gammaL_gens(ag):
    """generators of GammaL(3,q) as point permutations (matrices + Frobenius)."""
    F, q = ag.F, ag.q
    gens = []
    mats = []
    for i in range(3):
        for j in range(3):
            if i != j:
                M = [[int(r == c) for c in range(3)] for r in range(3)]; M[i][j] = 1; mats.append(M)
    # multiplicative generator of F_q^*
    g = next(a for a in range(2, q) if len({_pow(F, a, k) for k in range(q - 1)}) == q - 1) if q > 2 else 1
    for i in range(3):
        M = [[int(r == c) for c in range(3)] for r in range(3)]; M[i][i] = g; mats.append(M)
    for M in mats:
        gens.append([ag.pidx[tuple(_dot(F, M[r], p) for r in range(3))] for p in ag.points])
    if F.k > 1:  # Frobenius x -> x^p coordinatewise
        frob = [_pow(F, a, F.p) for a in range(q)]
        gens.append([ag.pidx[tuple(frob[c] for c in p)] for p in ag.points])
    return gens

def _pow(F, a, k):
    r = 1
    for _ in range(k): r = F.mul[r][a]
    return r

def dir_perms(ag, gens):
    """induced permutations of the direction indices."""
    out = []
    for g in gens:
        perm = []
        for d in ag.dirs:
            v = ag.points[g[ag.pidx[d]]]
            perm.append(ag.didx[ag.normalize_dir(v)])
        out.append(perm)
    return out

def subset_orbits(nd, perms, D):
    """orbits of D-subsets of range(nd) under the group generated by perms. Returns list of (rep, size)."""
    seen = {}
    orbits = []
    for comb in itertools.combinations(range(nd), D):
        if comb in seen: continue
        k = len(orbits); orb = [comb]; seen[comb] = k; stack = [comb]
        while stack:
            s = stack.pop()
            for p in perms:
                t = tuple(sorted(p[i] for i in s))
                if t not in seen:
                    seen[t] = k; stack.append(t); orb.append(t)
        orbits.append((min(orb), len(orb)))
    return orbits

def describe(ag, R):
    """collinearity structure of a set of directions: max number on a common projective line (plane through O)."""
    F = ag.F
    best = 0
    for n in ag.dirs:  # plane through origin with normal n
        c = sum(1 for d in R if _dot(F, n, ag.dirs[d]) == 0)
        best = max(best, c)
    return best

def build_model(ag, D, R, ub, planes=True, proj=True, objective=True, split=None):
    """split=(direction index e, line index k): additionally force the k-th line of direction e (used to cut a
    subcase into 16 sub-subcases for the CP-SAT cross-check; the 16 together are equivalent to the subcase)."""
    from ortools.sat.python import cp_model
    m = cp_model.CpModel()
    x = [m.NewBoolVar(f"x{i}") for i in range(len(ag.points))]
    y = [m.NewBoolVar(f"y{i}") for i in range(len(ag.lines))]
    for di in range(len(ag.dirs)):
        m.AddExactlyOne([y[l] for l in ag.lines_by_dir[di]])
    thru = [[] for _ in ag.points]
    for l, (di, pts) in enumerate(ag.lines):
        for p in pts:
            m.AddImplication(y[l], x[p]); thru[p].append(l)
    for p in range(len(ag.points)):
        m.AddBoolOr([y[l] for l in thru[p]]).OnlyEnforceIf(x[p])
        m.Add(sum(y[l] for l in thru[p]) <= D)
    O = tuple([0] * 3)
    for d in R:
        m.Add(y[ag.line_through(O, ag.dirs[d])] == 1)
    m.Add(sum(x) <= ub)
    if split is not None:
        e, k = split
        m.Add(y[ag.lines_by_dir[e][k]] == 1)
    if planes:
        from plane_f import get
        from solve_cpsat import planes_of
        f = get(ag.q); table = [f[r] for r in range(ag.q + 2)]
        for pts, lines in planes_of(ag):
            z = m.NewIntVar(0, ag.q + 1, ""); m.Add(z == sum(y[l] for l in lines))
            t = m.NewIntVar(0, ag.q * ag.q, ""); m.AddElement(z, table, t)
            m.Add(sum(x[p] for p in pts) >= t)
    if proj:
        from plane_f import get
        bm = get(ag.q)[ag.q + 1]  # planar Kakeya minimum
        for di in range(len(ag.dirs)):
            zs = []
            for l in ag.lines_by_dir[di]:
                z = m.NewBoolVar(""); pts = ag.lines[l][1]
                m.AddBoolOr([x[p] for p in pts]).OnlyEnforceIf(z)
                for p in pts: m.AddImplication(x[p], z)
                zs.append(z)
            m.Add(sum(zs) >= bm)
    if objective:
        m.Minimize(sum(x))
    return m, x, y

def solve_case(ag, D, R, ub, time_limit, workers, planes, proj, core, log=False, objective=True, split=None):
    from ortools.sat.python import cp_model
    m, x, y = build_model(ag, D, R, ub, planes, proj, objective, split)
    s = cp_model.CpSolver()
    s.parameters.max_time_in_seconds = time_limit
    s.parameters.num_workers = workers
    s.parameters.log_search_progress = log
    s.parameters.symmetry_level = 2
    if core: s.parameters.optimize_with_core = True
    t0 = time.time(); st = s.Solve(m); dt = time.time() - t0
    res = dict(status=s.StatusName(st), time=round(dt, 1), bound=int(round(s.BestObjectiveBound())) if objective else None)
    if st in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        S = [i for i in range(len(ag.points)) if s.Value(x[i])]
        ok, miss = is_kakeya(ag, S); assert ok, miss
        res["size"] = len(S); res["points"] = [ag.points[i] for i in S]
        res["lines"] = [sorted(ag.lines[l][1]) for l in range(len(ag.lines)) if s.Value(y[l])]
    return res

def write_cnf(ag, D, R, ub, fn, planes=False, proj=False):
    """DIMACS CNF of the subcase (for kissat/cadical with DRAT). Returns var maps."""
    from pysat.card import CardEnc, EncType
    from pysat.formula import IDPool
    pool = IDPool()
    x = [pool.id(("x", i)) for i in range(len(ag.points))]
    y = [pool.id(("y", i)) for i in range(len(ag.lines))]
    cls = []
    thru = [[] for _ in ag.points]
    for di in range(len(ag.dirs)):
        lits = [y[l] for l in ag.lines_by_dir[di]]
        cls.append(lits)
        cls += CardEnc.atmost(lits=lits, bound=1, vpool=pool, encoding=EncType.pairwise).clauses
    for l, (di, pts) in enumerate(ag.lines):
        for p in pts:
            cls.append([-y[l], x[p]]); thru[p].append(l)
    for p in range(len(ag.points)):
        cls.append([-x[p]] + [y[l] for l in thru[p]])
        cls += CardEnc.atmost(lits=[y[l] for l in thru[p]], bound=D, vpool=pool, encoding=EncType.seqcounter).clauses
    O = tuple([0] * 3)
    for d in R:
        cls.append([y[ag.line_through(O, ag.dirs[d])]])
    cls += CardEnc.atmost(lits=x, bound=ub, vpool=pool, encoding=EncType.totalizer).clauses
    if proj:
        from plane_f import get
        bm = get(ag.q)[ag.q + 1]
        for di in range(len(ag.dirs)):
            zs = []
            for l in ag.lines_by_dir[di]:
                z = pool.id(("z", l)); pts = ag.lines[l][1]
                cls.append([-z] + [x[p] for p in pts])
                for p in pts: cls.append([-x[p], z])
                zs.append(z)
            cls += CardEnc.atleast(lits=zs, bound=bm, vpool=pool, encoding=EncType.seqcounter).clauses
    if planes:
        from plane_f import get
        from solve_cpsat import planes_of
        f = get(ag.q)
        for pts, lines in planes_of(ag):
            ly = [y[l] for l in lines]
            lx = [x[p] for p in pts]
            for r in range(2, ag.q + 1):
                if f[r] == f[r - 1]: continue
                # a_r  <=  (sum ly >= r): encode atmost(r-1) under assumption not a_r : clauses of atmost(r-1) each OR a_r
                a = pool.id(("a", len(cls), r))
                for c in CardEnc.atmost(lits=ly, bound=r - 1, vpool=pool, encoding=EncType.seqcounter).clauses:
                    cls.append(c + [a])
                for c in CardEnc.atleast(lits=lx, bound=f[r], vpool=pool, encoding=EncType.seqcounter).clauses:
                    cls.append(c + [-a])
    with open(fn, "w") as fo:
        fo.write(f"p cnf {pool.top} {len(cls)}\n")
        for c in cls: fo.write(" ".join(map(str, c)) + " 0\n")
    return dict(nvars=pool.top, nclauses=len(cls), x=x, y=y)

def all_cases(ag):
    gens = gammaL_gens(ag)
    perms = dir_perms(ag, gens)
    q = ag.q
    Dmax = (ag.q ** 3) // (q - 1)  # trivial
    out = []
    for D in range(1, len(ag.dirs) + 1):
        if 1 + (q - 1) * D > 64: break
        out.append((D, subset_orbits(len(ag.dirs), perms, D)))
    return out

