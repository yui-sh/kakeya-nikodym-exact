    ap.add_argument("--out", default=None)
    ap.add_argument("--split", default=None, help="E:K  also force line K (0..q^2-1) of direction index E")
    a = ap.parse_args()
    ag = AG(3, a.q)
    gens = gammaL_gens(ag); perms = dir_perms(ag, gens)
    if a.list:
        from math import comb
        for D in range(1, 22):
            if 1 + (a.q - 1) * D > a.ub: break
            orbs = subset_orbits(len(ag.dirs), perms, D)
            assert sum(sz for _, sz in orbs) == comb(len(ag.dirs), D)
            print(f"D={D}: {len(orbs)} orbits; forced points {1+(a.q-1)*D}")
            for i, (rep, sz) in enumerate(orbs):
                print(f"   rep {i}: dirs {[ag.dirs[d] for d in rep]} orbit size {sz} max_coplanar {describe(ag, rep)}")
        sys.exit()
    orbs = subset_orbits(len(ag.dirs), perms, a.D)
    rep, sz = orbs[a.rep]
    if a.cnf:
        info = write_cnf(ag, a.D, rep, a.ub, a.cnf, a.planes, a.proj)
        print(json.dumps(dict(D=a.D, rep=a.rep, dirs=[ag.dirs[d] for d in rep], cnf=a.cnf, nvars=info["nvars"], nclauses=info["nclauses"])))
        sys.exit()
    split = tuple(map(int, a.split.split(":"))) if a.split else None
    res = solve_case(ag, a.D, rep, a.ub, a.time, a.workers, a.planes, a.proj, a.core, a.log, not a.feas, split)
    res.update(q=a.q, ub=a.ub, D=a.D, rep=a.rep, split=split, dirs=[ag.dirs[d] for d in rep], orbit_size=sz,
               max_coplanar=describe(ag, rep), planes=a.planes, proj=a.proj, core=a.core, workers=a.workers)
    print(json.dumps({k: v for k, v in res.items() if k not in ("points", "lines")}), flush=True)
    if a.out: json.dump(res, open(a.out, "w"))
