"""G-invariant minimum Kakeya sets in AG(3,q): collapse points/lines to G-orbits and solve exactly with CP-SAT.
Group elements are affine maps (M, b) over GF(q) given as 3x3 matrix + translation vector.
Families (--family): gl (conjugacy class reps of GL(3,q) as cyclic groups, + affine translates),
singer (subgroups of F_{q^3}^* acting by multiplication, with/without Frobenius), file (generators from json).
Each result line: {"name","order","npt_orbits","nline_orbits","status","size","bound","time"}.
Sets strictly smaller than --best are saved to solutions/."""
import argparse, json, time, sys, itertools, os
from multiprocessing import Pool
from ortools.sat.python import cp_model
from geom import AG, is_kakeya
from structure import matmul, det3, _dot, perm_order

def perm_of(ag, M, b):
    F = ag.F
    return [ag.pidx[ag.add(tuple(_dot(F, M[i], p) for i in range(3)), tuple(b))] for p in ag.points]

def orbits_of(nelem, gens):
    lab = [-1] * nelem; orbs = []
    for i in range(nelem):
        if lab[i] >= 0: continue
        k = len(orbs); lab[i] = k; stack = [i]; orb = [i]
        while stack:
            u = stack.pop()
            for g in gens:
                v = g[u]
                if lab[v] < 0:
                    lab[v] = k; stack.append(v); orb.append(v)
        orbs.append(orb)
    return lab, orbs

def group_order(gens, nelem):
    """order of the group generated by gens (point perms), by closure (capped)."""
    ident = tuple(range(nelem)); seen = {ident}; stack = [ident]
    while stack:
        g = stack.pop()
        for h in gens:
            k = tuple(h[i] for i in g)
            if k not in seen:
                seen.add(k); stack.append(k)
                if len(seen) > 200000: return -1
    return len(seen)

def solve_inv(ag, gens, time_limit=60, workers=2, ub=None, lb=None, hint=None, core=False):
    """gens: point perms. Exact min |S| over G-invariant Kakeya sets S."""
    plab, porbs = orbits_of(len(ag.points), gens)
    line_perms = [[ag.line_of[frozenset(g[p] for p in pts)] for (di, pts) in ag.lines] for g in gens]
    llab, lorbs = orbits_of(len(ag.lines), line_perms)
    m = cp_model.CpModel()
    X = [m.NewBoolVar(f"X{i}") for i in range(len(porbs))]
    Y = [m.NewBoolVar(f"Y{i}") for i in range(len(lorbs))]
    for di in range(len(ag.dirs)):
        m.AddBoolOr(list({Y[llab[l]] for l in ag.lines_by_dir[di]}))
    for k, lo in enumerate(lorbs):
        for po in {plab[p] for p in ag.lines[lo[0]][1]}:
            m.AddImplication(Y[k], X[po])
    # a chosen point orbit must lie on a chosen line orbit (tightening)
    cover = [set() for _ in porbs]
    for k, lo in enumerate(lorbs):
        for p in ag.lines[lo[0]][1]: cover[plab[p]].add(k)
    for i in range(len(porbs)):
        m.AddBoolOr([Y[k] for k in cover[i]]).OnlyEnforceIf(X[i])
    size = sum(len(po) * X[i] for i, po in enumerate(porbs))
    if ub is not None: m.Add(size <= ub)
    if lb is not None: m.Add(size >= lb)
    m.Minimize(size)
    if hint:
        hs = set(hint)
        for i, po in enumerate(porbs):
            m.AddHint(X[i], int(po[0] in hs))
    s = cp_model.CpSolver()
    s.parameters.max_time_in_seconds = time_limit
    s.parameters.num_workers = workers
    if core: s.parameters.optimize_with_core = True
    t0 = time.time(); st = s.Solve(m); dt = time.time() - t0
    res = dict(status=s.StatusName(st), npt_orbits=len(porbs), nline_orbits=len(lorbs), time=round(dt, 1),
               bound=int(round(s.BestObjectiveBound())) if st != cp_model.MODEL_INVALID else None)
    if st in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        S = [p for i, po in enumerate(porbs) if s.Value(X[i]) for p in po]
        ok, miss = is_kakeya(ag, S); assert ok, miss
        res["size"] = len(S); res["points"] = [ag.points[p] for p in S]
    else:
        res["size"] = None
    return res

# ---------- group families ----------
def companion(F, coeffs):
    """companion matrix of monic x^3 + c2 x^2 + c1 x + c0 (coeffs=(c0,c1,c2))."""
    c0, c1, c2 = coeffs; n = F.neg
    return [[0, 0, n[c0]], [1, 0, n[c1]], [0, 1, n[c2]]]

def gl_class_reps(F):
    """Conjugacy class reps of GL(3,q) via rational canonical form. Yields (name, M)."""
    q = F.q; a = F.add; m = F.mul; n = F.neg
    def polymul(p, r):  # low->high coefficient lists
        out = [0] * (len(p) + len(r) - 1)
        for i, x in enumerate(p):
            for j, y in enumerate(r): out[i + j] = a[out[i + j]][m[x][y]]
        return out
    def is_irred(p):  # p monic deg 2 or 3 over F_q: irreducible iff no root
        return all(_eval(F, p, t) != 0 for t in range(q))
    # cyclic classes: companion of every monic cubic f with f(0) != 0
    for c0 in range(1, q):
        for c1 in range(q):
            for c2 in range(q):
                f = [c0, c1, c2, 1]
                roots = [t for t in range(q) if _eval(F, f, t) == 0]
                if len(roots) == 3: typ = "split"
                elif len(roots) == 0: typ = "irred3"
                else:
                    # one root t: f = (x - t) g ; g irreducible or (x-t)^2 ...
                    typ = "lin*irred2" if len(set(roots)) == 1 and not _has_double(F, f, roots[0]) else "split-rep"
                yield (f"C[x^3+{c2}x^2+{c1}x+{c0}]:{typ}", companion(F, (c0, c1, c2)))
    # diag(a) + companion((x-a)(x-b))
    for aa in range(1, q):
        for bb in range(1, q):
            g = polymul([n[aa], 1], [n[bb], 1])
            C = [[0, n[g[0]]], [1, n[g[1]]]]
            yield (f"({aa})+C[(x-{aa})(x-{bb})]", [[aa, 0, 0], [0, C[0][0], C[0][1]], [0, C[1][0], C[1][1]]])
    for aa in range(2, q):
        yield (f"scalar({aa})", [[aa, 0, 0], [0, aa, 0], [0, 0, aa]])

def _eval(F, p, t):
    s = 0
    for c in reversed(p): s = F.add[F.mul[s][t]][c]
    return s
def _has_double(F, f, t):
    # f(t)=0; check f'(t)=0 : f' = 3x^2 c3 + 2 c2 x + c1 (coeffs low->high f=[c0,c1,c2,c3])
    c0, c1, c2, c3 = f
    a, m = F.add, F.mul
    three = a[a[1][1]][1]; two = a[1][1]
    d = a[a[m[three][m[c3][m[t][t]]]][m[two][m[c2][t]]]][c1]
    return d == 0

def rank(F, M):
    M = [row[:] for row in M]; r = 0; rows = len(M); cols = len(M[0])
    for c in range(cols):
        piv = next((i for i in range(r, rows) if M[i][c]), None)
        if piv is None: continue
        M[r], M[piv] = M[piv], M[r]
        iv = F.inv[M[r][c]]; M[r] = [F.mul[iv][x] for x in M[r]]
        for i in range(rows):
            if i != r and M[i][c]:
                f = M[i][c]; M[i] = [F.add[x][F.neg[F.mul[f][y]]] for x, y in zip(M[i], M[r])]
        r += 1
    return r

def affine_variants(F, M):
    """translation parts b up to conjugacy (coarse): 0; if 1 is an eigenvalue, reps of nonzero cosets of Im(M-I)."""
    I = [[int(i == j) for j in range(3)] for i in range(3)]
    A = [[F.add[M[i][j]][F.neg[I[i][j]]] for j in range(3)] for i in range(3)]
    k = 3 - rank(F, A)
    yield (0, 0, 0)
    if k == 0: return
    im = set()
    for v in itertools.product(range(F.q), repeat=3):
        im.add(tuple(_dot(F, A[i], v) for i in range(3)))
    # cosets: pick reps up to scalar (scalars centralize M)
    reps = []; covered = set(im)
    for v in itertools.product(range(F.q), repeat=3):
        if v in covered: continue
        reps.append(v)
        for lam in range(1, F.q):
            w = tuple(F.mul[lam][x] for x in v)
            for u in im: covered.add(tuple(F.add[x][y] for x, y in zip(w, u)))
    if k == 3: reps = reps[:1]
    for v in reps: yield v

class Fq3:
    """F_{q^3} = F_q[x]/(f) with f irreducible monic cubic; elements = triples (low->high)."""
    def __init__(self, F):
        self.F = F; q = F.q
        for c0 in range(1, q):
            for c1 in range(q):
                for c2 in range(q):
                    if all(_eval(F, [c0, c1, c2, 1], t) != 0 for t in range(q)):
                        self.f = (c0, c1, c2); break
                else: continue
                break
            else: continue
            break
        self.elems = list(itertools.product(range(q), repeat=3))
    def mul(self, u, v):
        F = self.F; prod = [0] * 5
        for i, x in enumerate(u):
            for j, y in enumerate(v): prod[i + j] = F.add[prod[i + j]][F.mul[x][y]]
        c0, c1, c2 = self.f
        for d in (4, 3):
            c = prod[d]
            if c:
                prod[d] = 0
                prod[d - 3] = F.add[prod[d - 3]][F.neg[F.mul[c][c0]]]
                prod[d - 2] = F.add[prod[d - 2]][F.neg[F.mul[c][c1]]]
                prod[d - 1] = F.add[prod[d - 1]][F.neg[F.mul[c][c2]]]
        return tuple(prod[:3])
    def pow(self, u, e):
        r = (1, 0, 0)
        while e:
            if e & 1: r = self.mul(r, u)
            u = self.mul(u, u); e >>= 1
        return r
    def mult_matrix(self, u):
        cols = [self.mul(u, (1, 0, 0)), self.mul(u, (0, 1, 0)), self.mul(u, (0, 0, 1))]
        return [[cols[j][i] for j in range(3)] for i in range(3)]
    def frob_matrix(self):
        q = self.F.q
        cols = [self.pow(e, q) for e in [(1, 0, 0), (0, 1, 0), (0, 0, 1)]]
        return [[cols[j][i] for j in range(3)] for i in range(3)]
    def primitive(self):
        Q = self.F.q ** 3
        for u in self.elems:
            if u == (0, 0, 0): continue
            o = 1; v = u
            while v != (1, 0, 0): v = self.mul(v, u); o += 1
            if o == Q - 1: return u

def divisors(n): return [d for d in range(1, n + 1) if n % d == 0]

def singer_groups(F):
    K = Fq3(F); q = F.q; Q1 = q ** 3 - 1
    w = K.primitive(); Fr = K.frob_matrix()
    for d in divisors(Q1):
        if d == 1: continue
        g = K.pow(w, Q1 // d)        # element of order d
        M = K.mult_matrix(g)
        yield (f"mult:ord{d}", [(M, (0, 0, 0))])
        yield (f"mult:ord{d}+Frob", [(M, (0, 0, 0)), (Fr, (0, 0, 0))])
    yield ("Frob", [(Fr, (0, 0, 0))])
    # Frobenius composed with multiplication (twisted): x -> g x^q, g of order d
    for d in divisors(Q1):
        if d == 1: continue
        g = K.pow(w, Q1 // d); M = matmul(F, K.mult_matrix(g), Fr)
        yield (f"twistFrob:ord{d}", [(M, (0, 0, 0))])

def run_one(args):
    n, q, name, gens_Mb, time_limit, workers, best, hint, ub, core = args
    ag = AG(n, q)
    gens = [perm_of(ag, M, b) for M, b in gens_Mb]
    order = group_order(gens, len(ag.points))
    res = solve_inv(ag, gens, time_limit, workers, ub=ub, hint=hint, core=core)
    res.update(name=name, order=order, q=q, gens=[{"M": M, "b": list(b)} for M, b in gens_Mb])
    pts = res.pop("points", None)
    if pts is not None and best is not None and res["size"] < best:
        fn = f"solutions/sym_n{n}_q{q}_{res['size']}_{abs(hash(name)) % 10**6}.json"
        json.dump({"n": n, "q": q, "points": pts, "group": name, "order": order, "status": res["status"]}, open(fn, "w"))
        res["saved"] = fn
    if pts is not None: res["points"] = pts
    return res

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--q", type=int, required=True)
    ap.add_argument("--family", default="gl")
    ap.add_argument("--time", type=float, default=60)
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--procs", type=int, default=2)
    ap.add_argument("--best", type=int, default=None, help="save sets strictly smaller than this")
    ap.add_argument("--affine", action="store_true", help="also translation variants (gl family)")
    ap.add_argument("--maxorder", type=int, default=10**9)
    ap.add_argument("--minorder", type=int, default=2)
    ap.add_argument("--gens", default=None, help="json file: list of groups {name, gens:[{M,b}]}")
    ap.add_argument("--hint", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--ub", type=int, default=None)
    ap.add_argument("--core", action="store_true")
    ap.add_argument("--names", default=None, help="comma-separated substrings: only groups whose name contains one")
    a = ap.parse_args()
    ag = AG(3, a.q); F = ag.F
    hint = None
    if a.hint:
        hint = [ag.pidx[tuple(p)] for p in json.load(open(a.hint))["points"]]
    groups = []
    if a.family == "gl":
        for name, M in gl_class_reps(F):
            if a.affine:
                for b in affine_variants(F, M):
                    groups.append((f"{name};b={b}", [(M, b)]))
            else:
                groups.append((name, [(M, (0, 0, 0))]))
    elif a.family == "singer":
        groups = list(singer_groups(F))
    elif a.family == "file":
        for g in json.load(open(a.gens)):
            groups.append((g["name"], [(x["M"], tuple(x["b"])) for x in g["gens"]]))
    # filter by order
    tasks = []
    for name, gens_Mb in groups:
        if a.names and not any(t in name for t in a.names.split(",")): continue
        gens = [perm_of(ag, M, b) for M, b in gens_Mb]
        o = group_order(gens, len(ag.points))
        if a.minorder <= o <= a.maxorder or o == -1:
            tasks.append((3, a.q, name, gens_Mb, a.time, a.workers, a.best, hint, a.ub, a.core))
    print(f"{len(tasks)} groups", file=sys.stderr, flush=True)
    out = a.out or f"out/sym_q{a.q}_{a.family}{'_aff' if a.affine else ''}.jsonl"
    with Pool(a.procs) as pool, open(out, "a") as fo:
        for res in pool.imap_unordered(run_one, tasks):
            r = {k: v for k, v in res.items() if k != "points"}
            print(json.dumps(r), flush=True)
            fo.write(json.dumps(res) + "\n"); fo.flush()
