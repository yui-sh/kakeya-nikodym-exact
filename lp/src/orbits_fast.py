"""Orbit representatives of D-subsets of PG(2,q) under PGammaL(3,q) (session IV).
Replaces maxdeg.subset_orbits (closure over all C(nd,D) subsets) by orderly generation with a canonical form
computed by vectorised minimisation over the WHOLE group (|PGL(3,5)| = 372000 permutations of the 31 directions,
stored as a numpy array). Level D reps = canonical forms of {rep_{D-1} + one point}, one point per orbit of the
stabiliser of rep_{D-1} on the complement.
Checks: sum of orbit sizes (|G|/|Stab|) = C(nd, D) and Burnside's count of orbits; for q=4 reproduces 3,5,8,10,13.
Cache: out/orbits_q{q}.json  (list per D of {"rep": [...], "size": n, "stab": s}).
Usage: orbits_fast.py --q 5 --Dmax 12"""
import argparse, json, os, sys, time, math
import numpy as np
from geom import AG
from maxdeg import gammaL_gens, dir_perms

def full_group(perms, nd):
    """all elements of the permutation group on range(nd) generated by perms, as an (N, nd) uint8 array."""
    ident = tuple(range(nd)); seen = {ident}; stack = [ident]
    while stack:
        g = stack.pop()
        for h in perms:
            k = tuple(h[i] for i in g)
            if k not in seen:
                seen.add(k); stack.append(k)
    return np.array(sorted(seen), dtype=np.uint8)

def expected_order(q, frob):
    gl = (q**3 - 1) * (q**3 - q) * (q**3 - q**2)
    return gl // (q - 1) * (frob if frob else 1)

class Orbits:
    def __init__(self, q):
        self.q = q
        ag = AG(3, q); self.ag = ag
        self.nd = len(ag.dirs)
        perms = dir_perms(ag, gammaL_gens(ag))
        t0 = time.time()
        self.G = full_group(perms, self.nd)
        self.N = len(self.G)
        assert self.N == expected_order(q, ag.F.k), (self.N, expected_order(q, ag.F.k))
        self.Gi = self.G.astype(np.int64)
        self.pow2 = (np.int64(1) << np.arange(self.nd, dtype=np.int64))
        print(f"q={q}: |PGammaL(3,q)| = {self.N} elements as permutations of {self.nd} directions ({time.time()-t0:.1f}s)", flush=True)

    def images(self, S):
        """bitmasks of g(S) for all g (array of length N)."""
        idx = self.Gi[:, list(S)]                   # N x D
        return self.pow2[idx].sum(axis=1)

    def canon(self, S):
        im = self.images(S)
        m = im.min()
        mask = sum(1 << s for s in S)
        stab = int((im == mask).sum())
        return int(m), stab

    @staticmethod
    def unmask(m):
        return tuple(i for i in range(64) if (m >> i) & 1)

    def stab_orbits_on_complement(self, S):
        """one representative per orbit of Stab(S) on the points outside S."""
        mask = sum(1 << s for s in S)
        im = self.images(S)
        stab_el = self.Gi[im == mask]                # k x nd
        comp = [p for p in range(self.nd) if p not in S]
        seen = set(); reps = []
        for p in comp:
            if p in seen: continue
            orb = set(int(v) for v in stab_el[:, p])
            seen |= orb; reps.append(p)
        return reps

    def levels(self, Dmax, verbose=True):
        """returns dict D -> list of (rep tuple, orbit size, stab order)."""
        out = {0: [((), 1, self.N)]}
        for D in range(1, Dmax + 1):
            t0 = time.time()
            found = {}
            for rep, sz, st in out[D - 1]:
                for p in self.stab_orbits_on_complement(rep):
                    S = tuple(sorted(rep + (p,)))
                    c, stab = self.canon(S)
                    if c not in found:
                        found[c] = (self.unmask(c), self.N // stab, stab)
            lv = sorted(found.values())
            total = sum(sz for _, sz, _ in lv)
            assert total == math.comb(self.nd, D), (D, total, math.comb(self.nd, D))
            out[D] = lv
            if verbose:
                print(f"D={D}: {len(lv)} orbits (sizes sum to C({self.nd},{D}) = {total}), {time.time()-t0:.1f}s", flush=True)
        return out

    def burnside(self, D):
        """number of orbits of D-subsets by Burnside: (1/|G|) sum_g #(D-subsets fixed by g), from cycle types."""
        from functools import lru_cache
        # cycle types
        types = {}
        for g in self.G:
            seen = [False] * self.nd; cyc = []
            for i in range(self.nd):
                if not seen[i]:
                    j, c = i, 0
                    while not seen[j]:
                        seen[j] = True; j = g[j]; c += 1
                    cyc.append(c)
            key = tuple(sorted(cyc)); types[key] = types.get(key, 0) + 1
        def fixed(cyc, D):
            # number of unions of cycles with total length D
            dp = [0] * (D + 1); dp[0] = 1
            for c in cyc:
                for s in range(D, c - 1, -1):
                    dp[s] += dp[s - c]
            return dp[D]
        tot = sum(cnt * fixed(cyc, D) for cyc, cnt in types.items())
        assert tot % self.N == 0
        return tot // self.N, len(types)

def load_or_compute(q, Dmax, verbose=True):
    fn = f"out/orbits_q{q}.json"
    cache = json.load(open(fn)) if os.path.exists(fn) else {}
    have = max((int(k) for k in cache), default=-1)
    if have >= Dmax:
        return {int(k): [(tuple(r["rep"]), r["size"], r["stab"]) for r in v] for k, v in cache.items() if int(k) <= Dmax}
    O = Orbits(q)
    lv = O.levels(Dmax, verbose)
    json.dump({str(D): [dict(rep=list(r), size=s, stab=st) for r, s, st in v] for D, v in lv.items()}, open(fn, "w"))
    return lv

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--q", type=int, default=5)
    ap.add_argument("--Dmax", type=int, default=12)
    ap.add_argument("--burnside", action="store_true")
    a = ap.parse_args()
    O = Orbits(a.q)
    lv = O.levels(a.Dmax)
    json.dump({str(D): [dict(rep=list(r), size=s, stab=st) for r, s, st in v] for D, v in lv.items()}, open(f"out/orbits_q{a.q}.json", "w"))
    if a.burnside:
        for D in range(1, a.Dmax + 1):
            nb, nt = O.burnside(D)
            print(f"D={D}: Burnside orbit count {nb} vs enumerated {len(lv[D])} -> {'OK' if nb == len(lv[D]) else 'MISMATCH'}", flush=True)
            assert nb == len(lv[D])
